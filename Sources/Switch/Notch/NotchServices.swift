import AppKit
import IOKit.pwr_mgt

/// Text copies for the notch's Clipboard tab, kept on disk for Settings → Notch → Keep clipboard
/// (1 day, 2 days or a week; pinned clips until unpinned). Copies that password managers mark
/// concealed or transient are never recorded.
/// ponytail: polls the pasteboard change count every 0.6 s (macOS has no change notification).
@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()

    struct Clip: Identifiable, Codable, Equatable {
        var id = UUID()
        var text: String
        var pinned = false
        /// When it was copied (or copied again). Missing in clips saved before history was kept.
        var date: Date?
    }

    @Published private(set) var clips: [Clip] = []

    /// Where pins lived before the whole history was saved; read once to carry them over.
    private static let legacyPinnedKey = "switch.notch.pinnedClips"
    /// Unpinned clips kept at most, whatever their age.
    private static let cap = 500
    private static let maxLength = 20_000
    private static let pollInterval: TimeInterval = 0.6
    /// Expired clips are dropped at most this often.
    private static let pruneInterval: TimeInterval = 60
    /// nspasteboard.org markers for secrets and machine-made copies.
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private var lastPrune = Date.distantPast
    private var saveWork: DispatchWorkItem?

    nonisolated private static var fileURL: URL {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0].appendingPathComponent("win-tab", isDirectory: true)
        return dir.appendingPathComponent("clipboard.json")
    }

    init() {
        let saved = (try? Data(contentsOf: Self.fileURL)).flatMap { try? JSONDecoder().decode([Clip].self, from: $0) }
        let legacy = UserDefaults.standard.data(forKey: Self.legacyPinnedKey).flatMap { try? JSONDecoder().decode([Clip].self, from: $0) }
        let now = Date()
        clips = (saved ?? legacy ?? []).map { var c = $0; c.date = c.date ?? now; return c }
        prune(force: true)
    }

    func setActive(_ active: Bool) {
        guard active != (timer != nil) else { return }
        if active {
            lastChange = NSPasteboard.general.changeCount
            timer = Timer.scheduledTimer(withTimeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
                MainActor.assumeIsolated { self?.poll() }
            }
            timer?.tolerance = Self.pollInterval * 0.1
        } else {
            timer?.invalidate()
            timer = nil
        }
    }

    private func poll() {
        prune(force: false)
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skippedTypes),
              let text = pb.string(forType: .string), text.count <= Self.maxLength,
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        let old = clips.first { $0.text == text }
        let rest = clips.filter { $0.text != text }
        let unpinned = rest.filter { !$0.pinned }.prefix(Self.cap - 1)
        clips = [Clip(id: old?.id ?? UUID(), text: text, pinned: old?.pinned ?? false, date: Date())] + rest.filter(\.pinned) + unpinned
        save()
    }

    /// The pasteboard as it is now is not a new copy (⌃⌥C copied and put things back).
    func ignoreCurrentChange() { lastChange = NSPasteboard.general.changeCount }

    /// Drops unpinned clips older than the retention setting (checked once a minute).
    func prune(force: Bool) {
        let now = Date()
        guard force || now.timeIntervalSince(lastPrune) >= Self.pruneInterval else { return }
        lastPrune = now
        let cutoff = now.addingTimeInterval(-SwitchPreferences.shared.notchClipboardRetention.seconds)
        let kept = clips.filter { $0.pinned || ($0.date ?? now) >= cutoff }
        guard kept.count != clips.count else { return }
        clips = kept
        save()
    }

    func copy(_ clip: Clip) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(clip.text, forType: .string)
        lastChange = pb.changeCount
        var fresh = clip
        fresh.date = Date()
        clips = [fresh] + clips.filter { $0.id != clip.id }
        save()
    }

    func togglePin(_ clip: Clip) {
        clips = clips.map { c in
            guard c.id == clip.id else { return c }
            var t = c
            t.pinned.toggle()
            return t
        }
        save()
    }

    func remove(_ clip: Clip) {
        clips = clips.filter { $0.id != clip.id }
        save()
    }

    /// Pins survive Clear.
    func clearUnpinned() {
        clips = clips.filter(\.pinned)
        save()
    }

    /// Written a moment after the last change, off the main thread, readable only by you.
    private func save() {
        saveWork?.cancel()
        let snapshot = clips
        let work = DispatchWorkItem {
            do {
                let url = Self.fileURL
                try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
                try JSONEncoder().encode(snapshot).write(to: url, options: [.atomic])
                try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            } catch {
                NSLog("win-tab: couldn't save clipboard history: \(error)")
            }
        }
        saveWork = work
        DispatchQueue.global(qos: .utility).asyncAfter(deadline: .now() + 1, execute: work)
    }
}

/// Files dropped on the notch, kept (by path, not copied) until you remove them, across relaunches.
@MainActor
final class FileShelf: ObservableObject {
    static let shared = FileShelf()
    private static let key = "switch.notch.shelf"

    @Published private(set) var urls: [URL]

    init() {
        let paths = UserDefaults.standard.stringArray(forKey: Self.key) ?? []
        urls = paths.filter { FileManager.default.fileExists(atPath: $0) }.map { URL(fileURLWithPath: $0) }
    }

    func add(_ new: [URL]) {
        let fresh = new.filter { $0.isFileURL && !urls.contains($0) }
        guard !fresh.isEmpty else { return }
        urls += fresh
        save()
    }

    func remove(_ url: URL) {
        urls = urls.filter { $0 != url }
        save()
    }

    func clear() {
        urls = []
        save()
    }

    /// A one-line note for the Files tab (e.g. Finder needs Automation access).
    @Published var notice: String?

    /// After a rename, the shelf keeps pointing at the file under its new name.
    func replace(_ old: URL, with new: URL) {
        guard let i = urls.firstIndex(of: old) else { return }
        urls[i] = new
        save()
    }

    func remove(_ some: Set<URL>) {
        urls = urls.filter { !some.contains($0) }
        save()
    }

    /// Drops files that were moved or deleted since they were shelved.
    func prune() {
        let kept = urls.filter { FileManager.default.fileExists(atPath: $0.path) }
        if kept != urls { urls = kept; save() }
    }

    private func save() { UserDefaults.standard.set(urls.map(\.path), forKey: Self.key) }
}

/// Keeps the display awake (like `caffeinate -d`) until switched off or win-tab quits.
@MainActor
final class KeepAwake: ObservableObject {
    static let shared = KeepAwake()
    @Published private(set) var isOn = false
    private var assertion: IOPMAssertionID = 0

    func toggle() {
        if isOn {
            IOPMAssertionRelease(assertion)
            isOn = false
            return
        }
        let result = IOPMAssertionCreateWithName(kIOPMAssertionTypePreventUserIdleDisplaySleep as CFString,
                                                 IOPMAssertionLevel(kIOPMAssertionLevelOn),
                                                 "win-tab Keep Awake" as CFString, &assertion)
        isOn = result == kIOReturnSuccess
        if !isOn { NSLog("win-tab: keep-awake assertion failed: \(result)") }
    }
}

/// One countdown at a time, shown on the notch; chimes and pops the notch when it ends.
@MainActor
final class NotchTimer: ObservableObject {
    static let shared = NotchTimer()
    static let presets = [1, 5, 10, 15, 25, 45]

    @Published private(set) var endsAt: Date?
    @Published private(set) var total: TimeInterval = 0
    var onFinish: () -> Void = {}
    private var ticker: Timer?

    var isRunning: Bool { endsAt != nil }
    func remaining(at now: Date = Date()) -> TimeInterval { max(0, (endsAt ?? now).timeIntervalSince(now)) }

    func start(minutes: Int) {
        total = TimeInterval(minutes * 60)
        endsAt = Date().addingTimeInterval(total)
        ticker?.invalidate()
        ticker = Timer.scheduledTimer(withTimeInterval: 1, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.tick() }
        }
    }

    func stop() {
        ticker?.invalidate()
        ticker = nil
        endsAt = nil
    }

    private func tick() {
        guard let endsAt, Date() >= endsAt else { return }
        stop()
        NSSound(named: "Glass")?.play()
        onFinish()
    }

    static func format(_ t: TimeInterval) -> String {
        let s = Int(t.rounded(.up))
        return s >= 3600 ? String(format: "%d:%02d:%02d", s / 3600, s / 60 % 60, s % 60) : String(format: "%d:%02d", s / 60, s % 60)
    }
}
